"""Pipeline step 7 (roadmap §2.2, decisions D1-D4 of docs/step7_design.md): variants of a base item.

Image-side variants are presentations (icpo.data.presentation) whose answers are recomputed from the labels:
    v1 swap      two adjacent slots exchanged, chosen so the answer changes (FLIP); none if no swap changes it
    v2 delete    one study removed and T-labels renumbered (D1), answer recomputed (SHIFT or SAME)
    v3 duplicate the last study appended once more (D2): every answer is unchanged (SAME)
    v4 donor     one slot the question depends on shows another patient's study (D3): CANNOT + flag inconsistent
Text-side variants (v5 impression rewrite, v6 indication rewording) are generated by a pinned language model in a
separate step and validated there; here they only reuse the base presentation.

Every choice that varies per item comes from a hash of the item id, so bundles are identical across runs.
"""

import hashlib

from icpo.data.presentation import CANNOT, DONOR, answer

TEL_NONE_INDEX = -2   # position of the "none" option in a TEL option list (CANNOT is last)


def _h(*parts) -> int:
    return int(hashlib.sha256("|".join(map(str, parts)).encode()).hexdigest(), 16)


def tel_options(item: dict, m: int) -> list[str]:
    """TEL options for a presentation with m slots: every interval, then the item's own 'none' text, then CANNOT."""
    none_text = item["options"][item["n"] - 1]
    return [f"T{i + 1} → T{i + 2}" for i in range(m - 1)] + [none_text, CANNOT]


def render(item: dict, slots: list[int], kind: str, relation: str | None = None) -> dict | None:
    """A variant record, or None if its answer is not determined by the labels."""
    ans = answer(item, slots)
    if ans is None:
        return None
    opts = tel_options(item, len(slots)) if item["family"] == "TEL" else list(item["options"])
    if ans not in opts:
        return None
    base = item["answer"]
    rel = relation or ("ABSTAIN" if ans == CANNOT else "SAME" if ans == base else "CHANGE")
    return {"variant": kind, "slots": list(slots), "options": opts, "answer": ans,
            "answer_letter": "ABCDEFGHIJ"[opts.index(ans)], "relation": rel,
            "flag": "inconsistent" if DONOR in slots else "ok"}


def v1_swap(item: dict) -> dict | None:
    n = item["n"]
    order = sorted(range(n - 1), key=lambda k: _h(item["qid"], "v1", k))
    for k in order:
        slots = list(range(n))
        slots[k], slots[k + 1] = slots[k + 1], slots[k]
        v = render(item, slots, "v1_swap")
        if v is not None and v["answer"] != item["answer"]:
            return {**v, "relation": "FLIP", "params": {"swapped": [k, k + 1]}}
    return None


def v2_delete(item: dict) -> dict | None:
    """Remove one study (renumbered). Prefer a deletion that changes the answer; never go below two studies."""
    n = item["n"]
    if n < 3:
        return None
    order = sorted(range(n), key=lambda k: _h(item["qid"], "v2", k))
    found = []
    for k in order:
        slots = [s for s in range(n) if s != k]
        v = render(item, slots, "v2_delete")
        if v is not None:
            found.append({**v, "params": {"deleted": k}})
    changed = [v for v in found if v["answer"] != item["answer"]]
    return (changed or found or [None])[0]


def v3_duplicate(item: dict) -> dict | None:
    n = item["n"]
    v = render(item, list(range(n)) + [n - 1], "v3_duplicate")
    if v is None or v["answer"] != item["answer"]:
        return None              # by construction this never happens; checked in tests
    return {**v, "params": {"duplicated": n - 1}}


def v4_slot(item: dict) -> int:
    """Slot (0-based) to receive the donor: one the question depends on, chosen by hash."""
    req = sorted(int(e) - 1 for e in item["required_evidence"])
    return req[_h(item["qid"], "v4") % len(req)]


def v4_donor(item: dict) -> dict | None:
    k = v4_slot(item)
    slots = list(range(item["n"]))
    slots[k] = DONOR
    v = render(item, slots, "v4_donor")
    if v is None or v["answer"] != CANNOT:
        return None
    return {**v, "params": {"donor_slot": k}}


# --- v4 donors ----------------------------------------------------------------------------------------------------

DONOR_MIN_PHASH = 28      # 75th percentile of phash distance between consecutive films of one patient (2026-10-08)
DONOR_MAX_ASPECT = 0.10   # |aspect ratio / replaced aspect ratio - 1|
DONOR_TRIES = 2000


class DonorPool:
    """Deterministic donor choice: same split, same view, similar aspect ratio, another patient, and a phash
    distance of at least DONOR_MIN_PHASH to the replaced film and to every other film in the window."""

    def __init__(self, hashes, split_of: dict):
        h = hashes.copy()
        h["split"] = h.subject_id.map(split_of)
        h = h.dropna(subset=["split"]).sort_values("dicom_id")
        self.info = {d: (int(p, 16), w / hh, v, s, int(sub), rel) for d, p, w, hh, v, s, sub, rel in
                     zip(h.dicom_id, h.phash, h.width, h.height, h.ViewPosition, h.split, h.subject_id, h.relpath)}
        self.buckets = {k: g.dicom_id.tolist() for k, g in h.groupby(["split", "ViewPosition"])}

    def pick(self, qid: str, replaced: str, window: list[str]) -> str | None:
        ph, ar, view, split, subj, _ = self.info[replaced]
        others = [self.info[d][0] for d in window]
        cands = self.buckets.get((split, view), [])
        for t in range(min(DONOR_TRIES, len(cands))):
            d = cands[_h(qid, "donor", t) % len(cands)]
            dph, dar, _, _, dsubj, _ = self.info[d]
            if dsubj == subj or abs(dar / ar - 1) > DONOR_MAX_ASPECT:
                continue
            if all(bin(dph ^ o).count("1") >= DONOR_MIN_PHASH for o in others):
                return d
        return None

    def relpath(self, dicom_id: str) -> str:
        return self.info[dicom_id][5]
